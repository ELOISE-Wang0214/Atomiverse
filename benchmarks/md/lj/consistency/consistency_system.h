#pragma once
/// @file benchmarks/md/lj/consistency/consistency_system.h
/// @brief Shared system + golden-file I/O for the cpu↔cuda LJ backend
///        consistency benchmark (manual-system §6 backend-consistency policy).
///
/// One source of truth for the parity system so the CPU reference
/// (`cpu_reference.cpp`) and the GPU comparison (`cuda_compare.cu`) evaluate
/// the *identical* configuration. Both backends build the frame from
/// `make_consistency_system()`, drive it with the SAME driver setup
/// (`ConsistencyParams`), and read the resulting energy + per-atom forces off
/// the returned `cpu::Frame` (the `cuda::md::MD` driver materializes to device
/// and writes the result back to the host frame, exactly as `bench_md_step.cu`
/// relies on).
///
/// The system is a 3×3×3 FCC argon crystal (a = 5.26 Å → 108 atoms) with a
/// deterministic sinusoidal jitter that breaks the lattice symmetry, so the
/// per-atom force field is non-trivial and asymmetric (a perfect FCC lattice
/// has vanishing net force per atom by symmetry — useless as a parity target).
/// LJ parameters are the canonical argon set shared with the `md/lj`
/// validation benches (ε = 0.0104 eV, σ = 3.4 Å, rc = 6.8 Å).

#include <cmath>
#include <cstdio>
#include <fstream>
#include <sstream>
#include <string>
#include <vector>

#include "atomiverse/core/mat3.h"
#include "atomiverse/cpu/frame/frame.h"

namespace atv_consistency {

// ── Canonical LJ argon parameters (shared with md/lj validation) ──────
inline constexpr double kEpsilon = 0.0104; ///< LJ ε [eV] (argon).
inline constexpr double kSigma = 3.4;      ///< LJ σ [Å] (argon).
inline constexpr double kCutoff = 6.8;     ///< LJ cutoff [Å] (2σ).
inline constexpr double kLattice = 5.26;   ///< FCC lattice constant [Å].
inline constexpr int kNCell = 3;           ///< FCC cells per edge → 108 atoms.
inline constexpr double kJitter = 0.05;    ///< Symmetry-breaking jitter [Å].
inline constexpr double kMassAr = 39.948;  ///< Argon mass [amu].

/// @brief Parameters that BOTH backends must set identically for the driver
///        replay to reach the same phase point.
struct ConsistencyParams {
    /// @brief Integration steps before the energy/force snapshot.
    ///
    /// `steps == 0` compares the post-setup force field on the exact input
    /// geometry — the tightest, least-chaotic comparison. `steps > 0` lets
    /// mixed-precision divergence accumulate along the trajectory; use it
    /// only to probe drift, and loosen the tolerances accordingly.
    int steps = 0;
    double dt = 0.5; ///< Timestep [fs] (only relevant when steps > 0).
};

/// @brief Build the deterministic 3×3×3 FCC argon parity system.
/// @return A host `cpu::Frame` with 108 jittered argon atoms and a cubic box.
inline ATV::cpu::Frame make_consistency_system() {
    using namespace ATV;
    const double a = kLattice;
    const double box_len = kNCell * a;
    const double basis[4][3] = {
        {0.0, 0.0, 0.0},
        {0.0, 0.5 * a, 0.5 * a},
        {0.5 * a, 0.0, 0.5 * a},
        {0.5 * a, 0.5 * a, 0.0},
    };

    std::vector<double> x, y, z;
    for (int ix = 0; ix < kNCell; ++ix)
        for (int iy = 0; iy < kNCell; ++iy)
            for (int iz = 0; iz < kNCell; ++iz)
                for (auto& b : basis) {
                    x.push_back(ix * a + b[0]);
                    y.push_back(iy * a + b[1]);
                    z.push_back(iz * a + b[2]);
                }

    const int n = static_cast<int>(x.size());
    cpu::Frame frame(n);
    for (int i = 0; i < n; ++i) {
        // Deterministic per-atom jitter to break FCC symmetry.
        frame.atoms.x[i] = x[i] + kJitter * std::sin(0.7 * i);
        frame.atoms.y[i] = y[i] + kJitter * std::sin(1.3 * i);
        frame.atoms.z[i] = z[i] + kJitter * std::sin(1.9 * i);
        frame.atoms.vx[i] = 0.0;
        frame.atoms.vy[i] = 0.0;
        frame.atoms.vz[i] = 0.0;
        frame.atoms.mass[i] = kMassAr;
        frame.atoms.type[i] = 0;
    }
    frame.box = Mat3::cubic(box_len);
    return frame;
}

// ── Golden file: energy [eV] + per-atom forces [eV/Å] ─────────────────
//
// Plain-text, full-double precision (%.17g). One `energy` line, then one
// `i fx fy fz` line per atom in row order. The CPU reference writes it; the
// GPU comparison reads it. NOT committed: the golden is regenerated by the
// CPU reference (our own reference backend), never hand-authored — a stale
// or fabricated golden would silently pass/fail a real regression.

struct Golden {
    double energy = 0.0;
    std::vector<double> fx, fy, fz;
    int n() const { return static_cast<int>(fx.size()); }
};

/// @brief Write a golden snapshot to `path` at full double precision.
/// @return true on success.
inline bool write_golden(const std::string& path, const Golden& g) {
    std::ofstream out(path);
    if (!out)
        return false;
    out << "# atomiverse cpu-reference LJ backend-consistency golden\n";
    out << "# system: FCC argon 3x3x3 (108 atoms), eps=" << kEpsilon
        << " sigma=" << kSigma << " rc=" << kCutoff << "\n";
    out << "# schema: 'energy <eV>' then per-atom 'i fx fy fz' [eV/Angstrom]\n";
    char buf[128];
    std::snprintf(buf, sizeof buf, "energy %.17g\n", g.energy);
    out << buf;
    for (int i = 0; i < g.n(); ++i) {
        std::snprintf(buf, sizeof buf, "%d %.17g %.17g %.17g\n", i, g.fx[i],
                      g.fy[i], g.fz[i]);
        out << buf;
    }
    return static_cast<bool>(out);
}

/// @brief Read a golden snapshot from `path`.
/// @return true on success; `g` is populated with energy + forces.
inline bool read_golden(const std::string& path, Golden& g) {
    std::ifstream in(path);
    if (!in)
        return false;
    std::string line;
    bool have_energy = false;
    while (std::getline(in, line)) {
        if (line.empty() || line[0] == '#')
            continue;
        std::istringstream ss(line);
        std::string tok;
        ss >> tok;
        if (tok == "energy") {
            ss >> g.energy;
            have_energy = true;
        } else {
            // 'i fx fy fz' — tok already holds the index.
            double fx, fy, fz;
            ss >> fx >> fy >> fz;
            g.fx.push_back(fx);
            g.fy.push_back(fy);
            g.fz.push_back(fz);
        }
    }
    return have_energy && g.n() > 0;
}

} // namespace atv_consistency
