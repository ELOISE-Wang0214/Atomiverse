"""Generate minao_data.h from PySCF's ANO-based MINAO trimming.

Output mirrors `pyscf.scf.hf.init_guess_by_minao` exactly so that the projected
density matrix is numerically identical to PySCF (to LAPACK round-off).

Usage:
    python tools/gen_minao_data.py > include/atomiverse/cpu/scf/minao_data.h
"""
from __future__ import annotations

import sys

import numpy as np
from pyscf import gto
from pyscf.scf import atom_hf


def minao_basis(stdsymb: str):
    """Return (occupations_per_ao, shells) where shells is
    [(l, primitives)] with primitives = [[alpha, c0, c1, ...], ...].
    """
    basis_add = gto.basis.load("ano", stdsymb)
    occ_all: list[float] = []
    shells: list[tuple[int, list[list[float]]]] = []
    for l in range(4):
        ndocc, frac = atom_hf.frac_occ(stdsymb, l)
        if ndocc <= 0 and frac == 0:
            continue
        degen = l * 2 + 1
        occ_l = [2.0] * ndocc + ([frac] if frac > 0 else [])
        if not occ_l:
            continue
        occ_all.extend(np.repeat(occ_l, degen).tolist())
        ano_l = next((e for e in basis_add if e[0] == l), None)
        if ano_l is None:
            continue
        n_keep = ndocc + (1 if frac > 0 else 0)
        primitives = [[row[0]] + row[1 : 1 + n_keep] for row in ano_l[1:]]
        shells.append((l, primitives))
    return occ_all, shells


ELEMENTS = [
    (1, "H"),
    (6, "C"),
    (7, "N"),
    (8, "O"),
    (9, "F"),
]


def main() -> None:
    lines: list[str] = []
    lines.append("/// @file cpu/scf/minao_data.h")
    lines.append("/// @brief MINAO basis data trimmed from ANO. Auto-generated by tools/gen_minao_data.py.")
    lines.append("///")
    lines.append("/// Matches pyscf.scf.hf.init_guess_by_minao tables bit-for-bit.")
    lines.append("/// Do NOT edit by hand -- regenerate via tools/gen_minao_data.py.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("namespace ATV {")
    lines.append("namespace cpu {")
    lines.append("namespace scf {")
    lines.append("namespace minao {")
    lines.append("")
    lines.append("/// @brief One contracted shell (single l, possibly multiple contraction columns).")
    lines.append("struct Shell {")
    lines.append("    int l;                ///< Angular momentum (0=s, 1=p, 2=d, 3=f).")
    lines.append("    int n_prim;           ///< Number of primitive Gaussians.")
    lines.append("    int n_contract;       ///< Number of contracted functions sharing the exponents.")
    lines.append("    const double* alpha;  ///< [n_prim] exponents.")
    lines.append("    const double* coeff;  ///< [n_prim * n_contract] contraction matrix, row-major (prim, contract).")
    lines.append("};")
    lines.append("")
    lines.append("/// @brief MINAO basis for one element.")
    lines.append("struct ElementBasis {")
    lines.append("    int n_shells;")
    lines.append("    int n_ao;                    ///< Total AOs = sum over shells of (2l+1)*n_contract.")
    lines.append("    const Shell* shells;")
    lines.append("    const double* occupations;   ///< [n_ao] fractional occupations (spin-averaged, RHF total).")
    lines.append("};")
    lines.append("")
    lines.append("/// @brief Whether element Z is supported (H, C, N, O, F).")
    lines.append("inline bool has_minao(int Z) {")
    zs = [e[0] for e in ELEMENTS]
    cond = " || ".join(f"Z == {z}" for z in zs)
    lines.append(f"    return {cond};")
    lines.append("}")
    lines.append("")
    lines.append("/// @brief Retrieve MINAO basis for element Z (throws in callers if unsupported).")
    lines.append("const ElementBasis* element_basis(int Z);")
    lines.append("")
    lines.append("} // namespace minao")
    lines.append("} // namespace scf")
    lines.append("} // namespace cpu")
    lines.append("} // namespace ATV")
    header_out = "\n".join(lines) + "\n"

    # ── generate .cpp with tables ──────────────────────────────────────
    src: list[str] = []
    src.append('#include "atomiverse/cpu/scf/minao_data.h"')
    src.append("")
    src.append("namespace ATV {")
    src.append("namespace cpu {")
    src.append("namespace scf {")
    src.append("namespace minao {")
    src.append("")

    for Z, sym in ELEMENTS:
        occ, shells = minao_basis(sym)
        tag = f"{sym}_{Z}"
        src.append(f"// ── {sym} (Z={Z}) ─────────────────────────────────────────────")
        for si, (l, prims) in enumerate(shells):
            n_prim = len(prims)
            n_contract = len(prims[0]) - 1
            src.append(
                f"static const double {tag}_sh{si}_alpha[{n_prim}] = {{"
            )
            src.append(
                "    " + ", ".join(f"{row[0]:.18e}" for row in prims)
            )
            src.append("};")
            coeff_flat: list[float] = []
            for row in prims:
                coeff_flat.extend(row[1:])
            src.append(
                f"static const double {tag}_sh{si}_coeff[{n_prim * n_contract}] = {{"
            )
            src.append(
                "    " + ", ".join(f"{c:.18e}" for c in coeff_flat)
            )
            src.append("};")
        # Shell table for this element
        src.append(f"static const Shell {tag}_shells[{len(shells)}] = {{")
        for si, (l, prims) in enumerate(shells):
            n_prim = len(prims)
            n_contract = len(prims[0]) - 1
            src.append(
                f"    {{{l}, {n_prim}, {n_contract}, {tag}_sh{si}_alpha, {tag}_sh{si}_coeff}},"
            )
        src.append("};")
        n_ao = len(occ)
        src.append(f"static const double {tag}_occ[{n_ao}] = {{")
        src.append(
            "    " + ", ".join(f"{o:.18e}" for o in occ)
        )
        src.append("};")
        src.append(
            f"static const ElementBasis {tag}_basis = {{{len(shells)}, {n_ao}, {tag}_shells, {tag}_occ}};"
        )
        src.append("")

    src.append("const ElementBasis* element_basis(int Z) {")
    src.append("    switch (Z) {")
    for Z, sym in ELEMENTS:
        tag = f"{sym}_{Z}"
        src.append(f"        case {Z}: return &{tag}_basis;")
    src.append("        default: return nullptr;")
    src.append("    }")
    src.append("}")
    src.append("")
    src.append("} // namespace minao")
    src.append("} // namespace scf")
    src.append("} // namespace cpu")
    src.append("} // namespace ATV")

    src_out = "\n".join(src) + "\n"

    mode = sys.argv[1] if len(sys.argv) > 1 else "header"
    if mode == "header":
        sys.stdout.write(header_out)
    elif mode == "src":
        sys.stdout.write(src_out)
    else:
        raise SystemExit(f"unknown mode: {mode}")


if __name__ == "__main__":
    main()
